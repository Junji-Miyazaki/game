// LANDER — 超軽量バンドラ（依存なし）
// 02_src のESモジュール群を1つのクラシックスクリプトに結合し、file:// でも動くようにする。
//   実行: node build.js  → 02_src/lander.bundle.js を生成
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const stripImports = (s) => s.replace(/^\s*import\b[^\n]*\n/gm, '');
const stripExport = (s) => s.replace(/\bexport\s+(?=(const|class|function|async|let|var)\b)/g, '');

// 閉じたスコープのモジュール（EXPEDITION）。中のトップレベルの名前は他のファイルと重なってよい（ミッションごとに GY・TGT・start など同名が多いため）。
// 出力: const <名前> = (function(){ …本文… ; return { 公開した名前 }; })();
// どのファイルからでも、ここに載ったファイルからの import { a, b as c } は const { a, b: c } = <名前>; に置き換える（他の import 行は消す＝同じ外側スコープにある）。
const SCOPED = {
  '02_src/expedition/harness.js': 'EXP_harness',
  '02_src/expedition/shell.js': 'EXP_shell',
  '02_src/expedition/m1_phobos.js': 'EXP_m1',
  '02_src/expedition/m2_enceladus.js': 'EXP_m2',
  '02_src/expedition/m3_ryugu.js': 'EXP_m3',
  '02_src/expedition/m4_comet.js': 'EXP_m4',
  '02_src/expedition/index.js': 'EXP_index',
};
const outerDeclared = new Set();   // 外側スコープで const { … } = EXP_x; 済みの名前（同じ名前を二度宣言しない）
const linkImports = (file, s) => s.replace(/^\s*import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?[^\n]*\n/gm, (m, names, spec) => {
  const target = path.posix.normalize(path.posix.join(path.posix.dirname(file), spec.replace(/[?#].*$/, '')));
  const mod = SCOPED[target];
  if (!mod) return m;   // 外側スコープのファイル: 後で stripImports が消す
  const list = names.split(',').map((x) => x.trim()).filter(Boolean).map((x) => { const [a, b] = x.split(/\s+as\s+/); return b ? a + ': ' + b : a; });
  const inner = !!SCOPED[file], use = inner ? list : list.filter((x) => { const n = x.split(':').pop().trim(); if (outerDeclared.has(n)) return false; outerDeclared.add(n); return true; });
  return use.length ? 'const { ' + use.join(', ') + ' } = ' + mod + ';\n' : '';
});
const exportedNames = (s) => { const out = []; s.replace(/^export\s+(?:async\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm, (m, n) => { out.push(n); return m; }); return out; };
const convert = (f) => {
  const src = read(f), linked = stripImports(linkImports(f, src));
  if (!SCOPED[f]) return stripExport(linked);
  if (/^export\s*\{/m.test(linked) || /^[ \t]+export\s/m.test(linked)) throw new Error(f + ': 閉じたスコープのファイルでは export { } や入れ子の export は使えない（build.js）');
  const names = exportedNames(linked);
  return 'const ' + SCOPED[f] + ' = (function () {\n' + stripExport(linked) + '\nreturn { ' + names.join(', ') + ' };\n})();';
};

// 結合順（依存順）。すべて同一IIFEスコープに展開する。新ファイルを足したらここにも追加する。
const FILES = [
  '02_src/version.js',
  '02_src/core/palette.js',
  '02_src/core/audio.js',
  '02_src/core/storage.js',
  '02_src/core/i18n.js',
  '02_src/core/engine.js',
  '02_src/bodies.js',
  '02_src/modules.js',
  '02_src/rings.js',
  '02_src/stars.js',
  '02_src/net.js',
  '02_src/debug.js',
  '02_src/autopilot.js',
  '02_src/ranking.js',
  '02_src/art.js',
  '02_src/howto.js',
  '02_src/patches.js',
  '02_src/bootfx.js',
  '02_src/music.js',
  '02_src/whatsnew.js',
  '02_src/expedition/harness.js',
  '02_src/expedition/shell.js',
  '02_src/expedition/m1_phobos.js',
  '02_src/expedition/m2_enceladus.js',
  '02_src/expedition/m3_ryugu.js',
  '02_src/expedition/m4_comet.js',
  '02_src/expedition/index.js',
  '02_src/expdata.js',
  '02_src/solarmap.js',
  '02_src/expscene.js',
  '02_src/title.js',
  '02_src/migrate.js',
  '02_src/pods.js',
  '02_src/game.js',
  '02_src/main.js',
];

let out = '// === LANDER bundle (auto-generated by build.js — do not edit) ===\n';
out += '(function(){\n"use strict";\n';
for (const f of FILES) {
  out += `\n// ---- ${f} ----\n`;
  out += convert(f) + '\n';
}
out += '})();\n';

const dest = '02_src/lander.bundle.js';
fs.writeFileSync(path.join(ROOT, dest), out, 'utf8');
console.log('built ' + dest + ' (' + out.length + ' bytes)');

// キャッシュ対策: GitHub Pages は max-age=600 で配信するため、同じURLだと古い版が使われ続けることがある。
// 中身のハッシュを ?v= として index.html の参照に刻み、中身が変わればURLも変わるようにする。
const crypto = require('crypto');
const hashOf = (rel) => crypto.createHash('sha1').update(fs.readFileSync(path.join(ROOT, rel))).digest('hex').slice(0, 10);
const indexPath = path.join(ROOT, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
const stamp = (h, rel) => h.replace(new RegExp(rel.replace(/[.]/g, '\\.') + '(\\?v=[0-9a-f]+)?', 'g'), rel + '?v=' + hashOf(rel));
const stamped = stamp(stamp(html, '02_src/lander.bundle.js'), '03_assets/style.css');
if (stamped !== html) fs.writeFileSync(indexPath, stamped, 'utf8');
console.log('stamped index.html (bundle ?v=' + hashOf(dest) + ', css ?v=' + hashOf('03_assets/style.css') + ')');
